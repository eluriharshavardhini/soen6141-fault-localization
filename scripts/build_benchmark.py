"""Assemble the final benchmark from mining + reproduction results (Sampling section of the
protocol), and write the full screening log and summary statistics.

usage: python scripts/build_benchmark.py [--work /home/user/work]
Inputs : data/mining/candidates.jsonl, data/mining/mining_log.csv, data/repro/repro_results.jsonl
Outputs: data/benchmark/instances.jsonl, data/benchmark/env/<id>.freeze.txt,
         data/screening_log.csv, data/screening_summary.md
"""
from __future__ import annotations

import argparse
import csv
import json
import random
import shutil
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KEEP_CAP = 10
SEED = 6141


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", default="/home/user/work")
    a = ap.parse_args()
    cands = {c["fix_commit"]: c for c in map(json.loads, open(ROOT / "data/mining/candidates.jsonl"))}
    repro = {}
    for line in open(ROOT / "data/repro/repro_results.jsonl"):
        r = json.loads(line)
        repro[r["fix_commit"]] = r  # last result wins (re-runs after harness fixes)

    passed = defaultdict(list)
    for sha, r in repro.items():
        if r["status"] == "kept":
            passed[cands[sha]["repo"]].append(sha)
    chosen = set()
    for repo, shas in passed.items():
        shas = sorted(shas)
        chosen.update(shas if len(shas) <= KEEP_CAP else random.Random(SEED).sample(shas, KEEP_CAP))

    out = ROOT / "data/benchmark"
    (out / "env").mkdir(parents=True, exist_ok=True)
    insts = []
    for sha in sorted(chosen, key=lambda s: (cands[s]["repo"], cands[s]["date"])):
        c, r = cands[sha], repro[sha]
        iid = f"{c['repo'].replace('/', '__')}-{sha[:10]}"
        freeze = Path(a.work) / sha[:12] / "out" / "freeze.txt"
        if freeze.exists():
            shutil.copy(freeze, out / "env" / f"{iid}.freeze.txt")
        insts.append({
            "instance_id": iid, "repo": c["repo"], "repo_dir": c["repo_dir"],
            "fix_commit": sha, "buggy_commit": c["buggy_commit"], "date": c["date"],
            "fix_subject": c["subject"],  # NOT shown to models (leaks the answer)
            "python": "3.12", "dep_pin_exclude_newer": r["dep_pin"],
            "test_files_run": r["tests_run"], "fail_to_pass": r["f2p"],
            "failure_output": r["buggy_failures"],  # model input: what the developer would see
            "src_files_changed": c["src_files"], "src_churn": c["src_churn"],
            "oracle": c["oracle"],
        })
    with open(out / "instances.jsonl", "w") as fh:
        for i in insts:
            fh.write(json.dumps(i) + "\n")

    # full screening log: every commit screened, with outcome
    rows = []
    for row in csv.DictReader(open(ROOT / "data/mining/mining_log.csv")):
        sha = row["commit"]
        if row["status"] == "candidate":
            if sha not in repro:
                row["dropped_by"], row["status"] = "attempt_cap", "not_attempted"
            elif repro[sha]["status"] != "kept":
                row["dropped_by"], row["status"] = "R_" + repro[sha]["reason"], "dropped"
            elif sha not in chosen:
                row["dropped_by"], row["status"] = "keep_cap_sampling", "valid_not_sampled"
            else:
                row["status"] = "kept"
        rows.append(row)
    with open(ROOT / "data/screening_log.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    repos = sorted({r["repo"] for r in rows})
    reasons = sorted({r["dropped_by"] or "KEPT" for r in rows}, key=lambda x: (x == "KEPT", x))
    cnt = Counter((r["repo"], r["dropped_by"] or "KEPT") for r in rows)
    lines = ["# Screening summary", "", "Generated by `scripts/build_benchmark.py`. One row per outcome, one column per repository.", "",
             "| Outcome | " + " | ".join(x.split("/")[1] for x in repos) + " | Total |",
             "|---|" + "---|" * (len(repos) + 1)]
    for rs in ["SCREENED"] + reasons:
        if rs == "SCREENED":
            vals = [sum(1 for r in rows if r["repo"] == rp) for rp in repos]
        else:
            vals = [cnt[(rp, rs)] for rp in repos]
        lines.append(f"| {rs} | " + " | ".join(map(str, vals)) + f" | {sum(vals)} |")
    att = Counter(cands[s]["repo"] for s in repro)
    val = Counter(cands[s]["repo"] for s in repro if repro[s]["status"] == "kept")
    lines += ["", "Reproduction yield (valid / attempted): " +
              ", ".join(f"{rp.split('/')[1]} {val[rp]}/{att[rp]}" for rp in repos if att[rp]), "",
              f"**Kept instances: {len(insts)}** from {len({i['repo'] for i in insts})} repositories: " +
              ", ".join(f"{k.split('/')[1]} {v}" for k, v in sorted(Counter(i['repo'] for i in insts).items()))]
    (ROOT / "data/screening_summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
